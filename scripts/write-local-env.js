#!/usr/bin/env node
'use strict';
/* ═══════════════════════════════════════════════════════════════════
   gIVEMEGAME.IO — Create/refresh .env.local for the local Supabase stack
   Použitie: npm run db:local:env   (after npm run db:local:start)

   Writes SUPABASE_URL / SUPABASE_ANON_KEY (local, public by design),
   SUPABASE_DB_URL, PORT=3100, NODE_ENV=development and copies every
   OPENAI_* setting from .env. Values are never printed. .env.local is
   git-ignored (.env.*). The service_role key is NOT written.
   ═══════════════════════════════════════════════════════════════════ */

const fs = require('fs');
const path = require('path');
const dotenv = require('dotenv');
const { parseEnvOutput, isLocalUrl } = require('./seed-local');
const { execSync } = require('child_process');

const REPO_ROOT = path.join(__dirname, '..');
const ENV_PATH = path.join(REPO_ROOT, '.env');
const LOCAL_ENV_PATH = path.join(REPO_ROOT, '.env.local');

function main() {
	let status;
	try {
		status = parseEnvOutput(execSync(
			`npx --yes supabase@3.2.0 status -o env --workdir "${REPO_ROOT}"`,
			{ cwd: REPO_ROOT, stdio: ['ignore', 'pipe', 'ignore'], encoding: 'utf8' }
		));
	} catch {
		throw new Error('Could not read `supabase status`. Start the stack first: npm run db:local:start');
	}
	if (!status.API_URL || !status.ANON_KEY || !status.DB_URL) {
		throw new Error('supabase status did not return API_URL, ANON_KEY and DB_URL.');
	}
	if (!isLocalUrl(status.API_URL) || !isLocalUrl(status.DB_URL)) {
		throw new Error('supabase status points to a non-local address; refusing.');
	}

	const base = fs.existsSync(ENV_PATH) ? dotenv.parse(fs.readFileSync(ENV_PATH)) : {};
	const openai = Object.entries(base).filter(([key]) => key.startsWith('OPENAI_'));

	// Keep the generated test-account password across regenerations.
	const previous = fs.existsSync(LOCAL_ENV_PATH) ? dotenv.parse(fs.readFileSync(LOCAL_ENV_PATH)) : {};

	const lines = [
		'# Local development only (git-ignored). Generated by scripts/write-local-env.js.',
		'# npm run dev:local loads this file before .env, so these values win.',
		`SUPABASE_URL=${status.API_URL}`,
		`SUPABASE_ANON_KEY=${status.ANON_KEY}`,
		`SUPABASE_DB_URL=${status.DB_URL}`,
		'PORT=3100',
		'NODE_ENV=development',
		'',
		'# Copied from .env',
		...openai.map(([key, value]) => `${key}=${JSON.stringify(value)}`),
		...(previous.LOCAL_TEST_PASSWORD ? ['', '# Password for the seeded local test accounts (local only)', `LOCAL_TEST_PASSWORD=${previous.LOCAL_TEST_PASSWORD}`] : []),
		''
	];
	fs.writeFileSync(LOCAL_ENV_PATH, lines.join('\n'), { encoding: 'utf8', mode: 0o600 });
	console.log(`.env.local written (${openai.length} OPENAI_* setting(s) copied from .env; values not shown).`);
}

try {
	main();
} catch (error) {
	console.error(`[write-local-env] ${error.message}`);
	process.exitCode = 1;
}
