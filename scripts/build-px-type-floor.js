#!/usr/bin/env node
'use strict';
/* ═══════════════════════════════════════════════════════════════════
   gIVEMEGAME.IO — type floor builder (Phase 3 type scale)
   Použitie: node scripts/build-px-type-floor.js         (zapíše súbor)
             node scripts/build-px-type-floor.js --check (exit 1, ak nie je aktuálny)

   style.css has ~190 rules with 5–13px text. Rewriting all of them by
   hand is risky, so this script reads style.css and writes
   public/ui/px-type-floor.css: for every rule with a small font-size it
   emits the same selector under body.px-v2 with
     - 12px when the rule uses the pixel font (Press Start 2P), the
       minimum for display text, and
     - 14px otherwise, the minimum for body text.
   @media wrappers are kept. px-apply.css (loaded later) then moves the
   key screens to the readable body font on purpose.
   Delete this file once the legacy rules in style.css are gone.
   ═══════════════════════════════════════════════════════════════════ */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'public', 'style.css');
const OUT = path.join(ROOT, 'public', 'ui', 'px-type-floor.css');
const DISPLAY_MIN = 12;
const BODY_MIN = 14;

/** Decorative text inside the drawn Tamagochi device: it is not read, and a bigger size would break the drawing. */
const SKIP = new Set([
	'.tamagochi-avatar-skin .tamagochi-brand',
	'.indiweb-logo',
]);

/** @param {string} css @returns {{ prelude: string, body: string }[]} top-level blocks */
function splitBlocks(css) {
	const out = [];
	let i = 0;
	while (i < css.length) {
		const open = css.indexOf('{', i);
		if (open === -1) break;
		let depth = 1;
		let j = open + 1;
		while (j < css.length && depth > 0) {
			if (css[j] === '{') depth += 1;
			else if (css[j] === '}') depth -= 1;
			j += 1;
		}
		out.push({ prelude: css.slice(i, open).trim(), body: css.slice(open + 1, j - 1) });
		i = j;
	}
	return out;
}

/** @param {string} decls @returns {number|null} font-size in px */
function fontSizePx(decls) {
	const m = /(?:^|;)\s*font-size:\s*([\d.]+)(px|rem|em)\b/.exec(decls);
	if (!m) return null;
	return Number(m[1]) * (m[2] === 'px' ? 1 : 16);
}

/** @param {string} prelude */
function scope(prelude) {
	return prelude.split(',').map((sel) => {
		const s = sel.trim();
		if (s.startsWith('body.light-mode')) return s.replace(/^body\.light-mode/, 'body.px-v2.light-mode');
		if (s.startsWith('body.')) return s.replace(/^body/, 'body.px-v2');
		if (s.startsWith('body ')) return s.replace(/^body /, 'body.px-v2 ');
		return `body.px-v2 ${s}`;
	}).join(',\n');
}

/** @param {string} css @param {string} indent */
function floorRules(css, indent = '') {
	const lines = [];
	for (const { prelude, body } of splitBlocks(css)) {
		if (prelude.startsWith('@keyframes') || prelude.startsWith('@font-face') || prelude.startsWith('@import')) continue;
		if (prelude.startsWith('@media') || prelude.startsWith('@supports')) {
			const inner = floorRules(body, `${indent}\t`);
			if (inner.length) lines.push(`${indent}${prelude} {`, ...inner, `${indent}}`);
			continue;
		}
		const px = fontSizePx(body);
		if (px === null) continue;
		const pixelFont = /Press Start 2P/i.test(body);
		const min = pixelFont ? DISPLAY_MIN : BODY_MIN;
		if (px >= min) continue;
		const selectors = prelude.split(',').map((s) => s.trim().replace(/\s+/g, ' ')).filter((s) => !SKIP.has(s));
		if (!selectors.length) continue;
		lines.push(`${indent}${scope(selectors.join(', ')).replace(/\n/g, `\n${indent}`)} { font-size: ${min}px; } /* was ${+px.toFixed(2)}px */`);
	}
	return lines;
}

function build() {
	const css = fs.readFileSync(SRC, 'utf8').replace(/\r\n/g, '\n').replace(/\/\*[\s\S]*?\*\//g, '');
	return [
		'/* Generated by scripts/build-px-type-floor.js from public/style.css. Do not edit by hand.',
		`   Type floor: pixel font >= ${DISPLAY_MIN}px, body text >= ${BODY_MIN}px (Phase 3). */`,
		'',
		...floorRules(css),
		'',
	].join('\n');
}

if (require.main === module) {
	const content = build();
	const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : null;
	if (process.argv.includes('--check')) {
		if (current !== content) {
			console.error('public/ui/px-type-floor.css is out of date (run node scripts/build-px-type-floor.js)');
			process.exit(1);
		}
		console.log('type floor up to date');
	} else if (current !== content) {
		fs.writeFileSync(OUT, content);
		console.log('wrote public/ui/px-type-floor.css');
	}
}

module.exports = { build, fontSizePx, splitBlocks, DISPLAY_MIN, BODY_MIN, SKIP };
