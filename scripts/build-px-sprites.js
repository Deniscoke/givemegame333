/** @param {string[]} grid @param {string} name */
function validateGrid(grid, name) {
	if (!Array.isArray(grid) || grid.length !== GRID) throw new Error(`${name}: expected ${GRID} rows, got ${grid && grid.length}`);
	grid.forEach((row, y) => {
		if (row.length !== GRID) throw new Error(`${name}: row ${y} has ${row.length} columns, expected ${GRID}`);
	});
}

/**
 * Path data for every cell matching `match`, one run per row segment.
 * @param {string[]} grid
 * @param {(ch: string) => boolean} match
 * @param {number} [dx] x offset
 */
function runsToPath(grid, match, dx = 0) {
	let d = '';
	grid.forEach((row, y) => {
		let x = 0;
		while (x < row.length) {
			if (!match(row[x])) { x += 1; continue; }
			let end = x;
			while (end < row.length && match(row[end])) end += 1;
			d += `M${x + dx} ${y}h${end - x}v1h-${end - x}z`;
			x = end;
		}
	});
	return d;
}

/** @param {string[]} grid */
function bobUp(grid) {
	return [...grid.slice(1), '.'.repeat(GRID)];
}

function buildIcons() {
	const symbols = Object.entries(ICONS).map(([name, grid]) => {
		validateGrid(grid, `icon ${name}`);
		return `\t<symbol id="i-${name}" viewBox="0 0 16 16"><path d="${runsToPath(grid, (c) => c === '#')}"/></symbol>`;
	});
	return [
		'<svg xmlns="http://www.w3.org/2000/svg" fill="currentColor" shape-rendering="crispEdges">',
		'\t<!-- Generated by scripts/build-px-sprites.js. Do not edit by hand. Own drawings, 16x16 grid. -->',
		...symbols,
		'</svg>',
		'',
	].join('\n');
}

/** @param {string} name @param {{ frames: string[][], bob?: boolean }} def */
function buildDecor(name, def) {
	const frameA = def.frames[0];
	const frameB = def.bob ? bobUp(frameA) : def.frames[1];
	if (!frameB) throw new Error(`decor ${name}: needs two frames or bob:true`);
	validateGrid(frameA, `decor ${name} frame A`);
	validateGrid(frameB, `decor ${name} frame B`);
	const colours = new Set([...frameA.join(''), ...frameB.join('')].filter((c) => c !== '.'));
	const paths = [...colours].sort().map((ch) => {
		if (!PALETTE[ch]) throw new Error(`decor ${name}: unknown palette letter "${ch}"`);
		const d = runsToPath(frameA, (c) => c === ch) + runsToPath(frameB, (c) => c === ch, GRID);
		return `\t<path fill="${PALETTE[ch]}" d="${d}"/>`;
	});
	return [
		'<svg xmlns="http://www.w3.org/2000/svg" width="32" height="16" viewBox="0 0 32 16" shape-rendering="crispEdges">',
		'\t<!-- Generated by scripts/build-px-sprites.js. Two 16x16 frames side by side. -->',
		...paths,
		'</svg>',
		'',
	].join('\n');
}

/** @returns {Map<string, string>} absolute path → content */
function buildAll() {
	const out = new Map();
	out.set(ICONS_OUT, buildIcons());
	for (const [name, def] of Object.entries(DECOR)) out.set(path.join(DECOR_DIR, `${name}.svg`), buildDecor(name, def));
	return out;
}

if (require.main === module) {
	const check = process.argv.includes('--check');
	const stale = [];
	for (const [file, content] of buildAll()) {
		const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') : null;
		if (current === content) continue;
		if (check) { stale.push(path.relative(ROOT, file)); continue; }
		fs.mkdirSync(path.dirname(file), { recursive: true });
		fs.writeFileSync(file, content);
		console.log(`wrote ${path.relative(ROOT, file)}`);
	}
	if (check && stale.length) {
		console.error(`pixel sprites are out of date: ${stale.join(', ')} (run node scripts/build-px-sprites.js)`);
		process.exit(1);
	}
	if (check) console.log('pixel sprites up to date');
}

